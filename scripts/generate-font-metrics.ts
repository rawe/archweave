// Generates src/shared/diagram/plexMetrics.ts from the static IBM Plex Sans files in assets/fonts.
//
//   npx tsx scripts/generate-font-metrics.ts
//
// The table holds the advance width of every glyph the fonts map below U+3000, for the three weights
// diagrams use. Text measuring and wrapping read it in the browser and on the server, so both wrap alike.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WEIGHTS = { 400: 'IBMPlexSans-Regular.ttf', 500: 'IBMPlexSans-Medium.ttf', 600: 'IBMPlexSans-SemiBold.ttf' } as const;
const LIMIT = 0x3000;

interface Font {
  unitsPerEm: number;
  ascender: number;
  descender: number;
  capHeight: number;
  xHeight: number;
  advances: Map<number, number>;
}

function readFont(file: string): Font {
  const data = fs.readFileSync(file);
  const tables = new Map<string, number>();
  for (let i = 0; i < data.readUInt16BE(4); i++) {
    const record = 12 + i * 16;
    tables.set(data.toString('latin1', record, record + 4), data.readUInt32BE(record + 8));
  }
  const table = (tag: string): number => {
    const offset = tables.get(tag);
    if (offset === undefined) throw new Error(`${file}: no ${tag} table`);
    return offset;
  };
  const hhea = table('hhea');
  const os2 = table('OS/2');
  const hmtx = table('hmtx');
  const metricCount = data.readUInt16BE(hhea + 34);
  const advanceOf = (glyph: number): number => data.readUInt16BE(hmtx + Math.min(glyph, metricCount - 1) * 4);

  const advances = new Map<number, number>();
  const cmap = table('cmap');
  for (let i = 0; i < data.readUInt16BE(cmap + 2); i++) {
    const record = cmap + 4 + i * 8;
    const platform = data.readUInt16BE(record);
    const sub = cmap + data.readUInt32BE(record + 4);
    if (platform !== 3 && platform !== 0) continue;
    const format = data.readUInt16BE(sub);
    if (format === 4) {
      const segments = data.readUInt16BE(sub + 6) / 2;
      const ends = sub + 14;
      const starts = ends + segments * 2 + 2;
      const deltas = starts + segments * 2;
      const offsets = deltas + segments * 2;
      for (let s = 0; s < segments; s++) {
        const end = data.readUInt16BE(ends + s * 2);
        const start = data.readUInt16BE(starts + s * 2);
        const delta = data.readInt16BE(deltas + s * 2);
        const rangeOffset = data.readUInt16BE(offsets + s * 2);
        for (let code = start; code <= end && code < LIMIT; code++) {
          let glyph: number;
          if (rangeOffset === 0) glyph = (code + delta) & 0xffff;
          else {
            glyph = data.readUInt16BE(offsets + s * 2 + rangeOffset + (code - start) * 2);
            if (glyph !== 0) glyph = (glyph + delta) & 0xffff;
          }
          if (glyph !== 0) advances.set(code, advanceOf(glyph));
        }
      }
    } else if (format === 12) {
      for (let g = 0; g < data.readUInt32BE(sub + 12); g++) {
        const group = sub + 16 + g * 12;
        const start = data.readUInt32BE(group);
        const end = data.readUInt32BE(group + 4);
        const first = data.readUInt32BE(group + 8);
        for (let code = start; code <= end && code < LIMIT; code++) advances.set(code, advanceOf(first + code - start));
      }
    }
  }
  return {
    unitsPerEm: data.readUInt16BE(table('head') + 18),
    ascender: data.readInt16BE(hhea + 4),
    descender: data.readInt16BE(hhea + 6),
    capHeight: data.readInt16BE(os2 + 88),
    xHeight: data.readInt16BE(os2 + 86),
    advances,
  };
}

const fonts = Object.entries(WEIGHTS).map(([weight, file]) => ({ weight, font: readFont(path.join(root, 'assets/fonts', file)) }));
const regular = fonts[0]!.font;
const codes = [...regular.advances.keys()].filter((code) => code >= 0x20 && fonts.every(({ font }) => font.advances.has(code))).sort((a, b) => a - b);

const runs: [number, number][] = [];
for (const code of codes) {
  const last = runs.at(-1);
  if (last && last[0] + last[1] === code) last[1]++;
  else runs.push([code, 1]);
}

const average = (font: Font): number => {
  let sum = 0;
  for (let code = 0x61; code <= 0x7a; code++) sum += font.advances.get(code) ?? 0;
  return Math.round(sum / 26);
};

function wrapped(values: (number | string)[], indent: string): string {
  const lines: string[] = [];
  let line = indent;
  for (const value of values) {
    const piece = `${value},`;
    if (line.length + piece.length > 150) {
      lines.push(line);
      line = indent;
    }
    line += piece;
  }
  lines.push(line);
  return lines.join('\n');
}

const out = `// Generated by scripts/generate-font-metrics.ts from IBM Plex Sans 3.006. Do not edit.

/** Font units per em; every width below is in these units. */
export const UNITS_PER_EM = ${regular.unitsPerEm};
export const ASCENDER = ${regular.ascender};
export const DESCENDER = ${regular.descender};
export const CAP_HEIGHT = ${regular.capHeight};
export const X_HEIGHT = ${regular.xHeight};

/** Width assumed for a character the table does not know, per weight: the average lowercase letter. */
export const FALLBACK_ADVANCE: Record<400 | 500 | 600, number> = { ${fonts.map(({ weight, font }) => `${weight}: ${average(font)}`).join(', ')} };

/** Covered code points as [first, count] runs, in ascending order. */
export const RUNS: readonly (readonly [number, number])[] = [
${wrapped(
  runs.map(([start, count]) => `[${start},${count}]`),
  '  ',
)}
];

/** Advance widths per weight, in the order the runs list their code points. */
export const ADVANCES: Record<400 | 500 | 600, readonly number[]> = {
${fonts.map(({ weight, font }) => `  ${weight}: [\n${wrapped(codes.map((code) => font.advances.get(code)!), '    ')}\n  ],`).join('\n')}
};
`;

const target = path.join(root, 'src/shared/diagram/plexMetrics.ts');
fs.writeFileSync(target, out);
console.log(`${path.relative(root, target)}: ${codes.length} code points in ${runs.length} runs`);
